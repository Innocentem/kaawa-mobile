-- 1. Profiles table (linked to auth.users)
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  full_name text not null,
  phone_number text unique not null,
  district text not null,
  user_type text not null check (user_type in ('farmer', 'buyer', 'admin')),
  village text,
  profile_picture_url text,
  latitude float8,
  longitude float8,
  must_change_password boolean default false,
  suspended_until timestamptz,
  suspension_reason text,
  created_at timestamptz default now()
);

-- Enable RLS on profiles
alter table public.profiles enable row level security;

do $$
begin
  if not exists (select 1 from pg_policies where policyname = 'Public profiles are viewable by everyone.' and tablename = 'profiles') then
    create policy "Public profiles are viewable by everyone." on public.profiles for select using (true);
  end if;
  if not exists (select 1 from pg_policies where policyname = 'Users can insert their own profile.' and tablename = 'profiles') then
    create policy "Users can insert their own profile." on public.profiles for insert with check (auth.uid() = id);
  end if;
  if not exists (select 1 from pg_policies where policyname = 'Users can update own profile.' and tablename = 'profiles') then
    create policy "Users can update own profile." on public.profiles for update using (auth.uid() = id);
  end if;
end $$;

-- 2. Coffee Stock table
create table if not exists public.coffee_stock (
  id bigint generated by default as identity primary key,
  farmer_id uuid references public.profiles(id) on delete cascade not null,
  coffee_type text not null,
  quantity float8 not null, -- Total initial quantity
  quantity_remaining float8, -- How much is left (defaults to quantity)
  price_per_kg float8 not null,
  coffee_picture_url text,
  description text default '',
  is_sold boolean default false,
  created_at timestamptz default now()
);

-- Trigger to set initial quantity_remaining
create or replace function public.set_initial_quantity_remaining()
returns trigger as $$
begin
  if NEW.quantity_remaining is null then
    NEW.quantity_remaining := NEW.quantity;
  end if;
  return NEW;
end;
$$ language plpgsql;

drop trigger if exists on_coffee_stock_insert on public.coffee_stock;
create trigger on_coffee_stock_insert
  before insert on public.coffee_stock
  for each row execute procedure public.set_initial_quantity_remaining();

alter table public.coffee_stock enable row level security;

do $$
begin
  if not exists (select 1 from pg_policies where policyname = 'Coffee stock is viewable by everyone.' and tablename = 'coffee_stock') then
    create policy "Coffee stock is viewable by everyone." on public.coffee_stock for select using (true);
  end if;
  if not exists (select 1 from pg_policies where policyname = 'Farmers can manage their own stock.' and tablename = 'coffee_stock') then
    create policy "Farmers can manage their own stock." on public.coffee_stock for all using (auth.uid() = farmer_id);
  end if;
end $$;

