-- TRIGGER for automatic profile creation on signup
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, full_name, phone_number, district, user_type)
  values (
    new.id,
    new.raw_user_meta_data->>'full_name',
    new.raw_user_meta_data->>'phone_number',
    new.raw_user_meta_data->>'district',
    new.raw_user_meta_data->>'user_type'
  );
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- TRIGGER for notifying followers of new stock
create or replace function public.notify_followers_of_new_stock()
returns trigger as $$
begin
  insert into public.notifications (user_id, title, content, type, metadata)
  select
    f.user_id,
    'New Coffee Listing!',
    p.full_name || ' just posted a new ' || NEW.coffee_type || ' listing.',
    'stock_update',
    jsonb_build_object('stock_id', NEW.id)
  from public.favorites f
  join public.profiles p on p.id = NEW.farmer_id
  where f.favorite_user_id = NEW.farmer_id;

  return NEW;
end;
$$ language plpgsql security definer;

drop trigger if exists on_coffee_stock_created on public.coffee_stock;
create trigger on_coffee_stock_created
  after insert on public.coffee_stock
  for each row execute procedure public.notify_followers_of_new_stock();

-- TRIGGER for notifying users when a sale is completed
create or replace function public.notify_buyer_of_sale_completion()
returns trigger as $$
declare
  buyer_id uuid;
  farmer_name text;
begin
  -- When a message is updated to be marked as handled/completed (hypothetically via metadata)
  -- In this app, 'Complete Sale' updates coffee_stock.
  -- To notify a specific buyer, we should really update the message that initiated the request.

  -- Let's define that when purchase_request_data has "status": "completed" added to it.
  if (NEW.purchase_request_data->>'status' = 'completed' and (OLD.purchase_request_data->>'status' is null or OLD.purchase_request_data->>'status' != 'completed')) then

    buyer_id := NEW.sender_id;

    select full_name into farmer_name from public.profiles where id = NEW.receiver_id;

    insert into public.notifications (user_id, title, content, type, metadata)
    values (
      buyer_id,
      'Sale Completed!',
      'Farmer ' || farmer_name || ' has confirmed your purchase request.',
      'sale_completed',
      jsonb_build_object('message_id', NEW.id, 'farmer_id', NEW.receiver_id)
    );
  end if;

  return NEW;
end;
$$ language plpgsql security definer;

drop trigger if exists on_purchase_request_completed on public.messages;
create trigger on_purchase_request_completed
  after update on public.messages
  for each row execute procedure public.notify_buyer_of_sale_completion();

-- TRIGGER for notifying users when they receive a review
create or replace function public.notify_user_of_review()
returns trigger as $$
declare
  target_user_id uuid;
  reviewer_name text;
  review_type text;
begin
  -- Get reviewer name
  select full_name into reviewer_name from public.profiles where id = NEW.reviewer_id;

  if NEW.reviewed_user_id is not null then
    target_user_id := NEW.reviewed_user_id;
    review_type := 'user_review';
  else
    -- Get farmer_id from coffee_stock
    select farmer_id into target_user_id from public.coffee_stock where id = NEW.coffee_stock_id;
    review_type := 'product_review';
  end if;

  if target_user_id is not null then
    insert into public.notifications (user_id, title, content, type, metadata)
    values (
      target_user_id,
      'New Review Received!',
      reviewer_name || ' left you a ' || NEW.rating || '-star review.',
      'review',
      jsonb_build_object(
        'review_id', NEW.id,
        'reviewer_id', NEW.reviewer_id,
        'review_type', review_type,
        'coffee_stock_id', NEW.coffee_stock_id
      )
    );
  end if;

  return NEW;
end;
$$ language plpgsql security definer;

drop trigger if exists on_review_created on public.reviews;
create trigger on_review_created
  after insert on public.reviews
  for each row execute procedure public.notify_user_of_review();

-- TRIGGER for notifying farmers when a buyer shows interest
create or replace function public.notify_farmer_of_interest()
returns trigger as $$
declare
  target_farmer_id uuid;
  buyer_name text;
  coffee_name text;
begin
  -- Get the farmer ID and coffee type
  select farmer_id, coffee_type into target_farmer_id, coffee_name
  from public.coffee_stock where id = NEW.coffee_stock_id;

  -- Get the buyer name
  select full_name into buyer_name from public.profiles where id = NEW.buyer_id;

  if target_farmer_id is not null then
    insert into public.notifications (user_id, title, content, type, metadata)
    values (
      target_farmer_id,
      'New Product Interest!',
      buyer_name || ' is interested in your ' || coffee_name || '.',
      'interest',
      jsonb_build_object(
        'stock_id', NEW.coffee_stock_id,
        'buyer_id', NEW.buyer_id
      )
    );
  end if;

  return NEW;
end;
$$ language plpgsql security definer;

drop trigger if exists on_interest_created on public.interested_buyers;
create trigger on_interest_created
  after insert on public.interested_buyers
  for each row execute procedure public.notify_farmer_of_interest();

